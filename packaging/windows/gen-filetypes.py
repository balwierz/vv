#!/usr/bin/env python3
"""Write packaging/windows/filetypes.wxs: the MSI's file-type registration,
from the extensions `vv --formats --json` lists.

    gen-filetypes.py VV > packaging/windows/filetypes.wxs

The installer registers one ProgId, vv.DataFile, opening a file in vvg, and
lists it under each extension's OpenWithProgids and under vvg.exe's
SupportedTypes. It never writes an extension's default handler, so a type
another program owns (Excel for .csv / .xlsx, …) keeps it; Explorer offers
vv Viewer under "Open with", and asks once for a type nothing owns.

Left out: suffixes Windows cannot register (`.zarr.zip` is `.zip`; a `.zarr`
store is a directory) and plain text / Markdown, which vv reads but which
belong to text editors. tests/run_tests.sh regenerates the file and diffs it.
"""
import json
import subprocess
import sys

SKIP = {".zarr", ".txt", ".text", ".log", ".md", ".markdown", ".mdown", ".mkd"}


def extensions(vv):
    out = subprocess.run([vv, "--formats", "--json"], capture_output=True, text=True, check=True).stdout
    exts = set()
    for fmt in json.loads(out):
        for e in fmt["extensions"]:
            e = e.lower()
            if e.count(".") == 1 and e not in SKIP:
                exts.add(e)
    return sorted(exts)


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: gen-filetypes.py VV")
    exts = extensions(sys.argv[1])
    cls = r"Software\Classes"
    open_cmd = '&quot;[INSTALLFOLDER]vvg.exe&quot; &quot;%1&quot;'
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!--",
        "  Generated by packaging/windows/gen-filetypes.py from vv's format table;",
        "  do not edit. vv Viewer (vvg.exe) under Explorer's \"Open with\" for",
        "  %d extensions, without taking over any extension's default program." % len(exts),
        "-->",
        '<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">',
        "  <Fragment>",
        '    <ComponentGroup Id="FileTypes" Directory="INSTALLFOLDER">',
        '      <Component Id="FileTypeRegistration">',
        '        <RegistryValue Root="HKLM" Key="%s\\vv.DataFile" Type="string"' % cls,
        '                       Value="Data file (vv)" KeyPath="yes" />',
        '        <RegistryValue Root="HKLM" Key="%s\\vv.DataFile\\DefaultIcon" Type="string"' % cls,
        '                       Value="[INSTALLFOLDER]vvg.exe,0" />',
        '        <RegistryValue Root="HKLM" Key="%s\\vv.DataFile\\shell\\open\\command" Type="string"' % cls,
        '                       Value="%s" />' % open_cmd,
        '        <RegistryValue Root="HKLM" Key="%s\\Applications\\vvg.exe" Name="FriendlyAppName"' % cls,
        '                       Type="string" Value="vv Viewer" />',
        '        <RegistryValue Root="HKLM" Key="%s\\Applications\\vvg.exe\\shell\\open\\command" Type="string"' % cls,
        '                       Value="%s" />' % open_cmd,
        '        <RemoveRegistryKey Root="HKLM" Key="%s\\vv.DataFile" Action="removeOnUninstall" />' % cls,
        '        <RemoveRegistryKey Root="HKLM" Key="%s\\Applications\\vvg.exe" Action="removeOnUninstall" />' % cls,
    ]
    for e in exts:
        lines.append('        <RegistryValue Root="HKLM" Key="%s\\%s\\OpenWithProgids" Name="vv.DataFile" Type="string" Value="vv" />'
                     % (cls, e))
        lines.append('        <RegistryValue Root="HKLM" Key="%s\\Applications\\vvg.exe\\SupportedTypes" Name="%s" Type="string" Value="vv" />'
                     % (cls, e))
    lines += [
        "      </Component>",
        "    </ComponentGroup>",
        "  </Fragment>",
        "</Wix>",
    ]
    print("\n".join(lines))


if __name__ == "__main__":
    main()
